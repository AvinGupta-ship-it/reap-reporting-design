def fetch_usaspending(manifest: Manifest, fiscal_years: list[int]) -> None:
    """Assistance awards under Assistance Listing 10.868 (amount, State, type description)."""
    for fy in fiscal_years:
        dest = RAW / "usaspending" / f"reap_10868_fy{fy}.json"
        if manifest.has_valid(dest):
            continue
        body: dict[str, Any] = {
            "filters": {
                "award_type_codes": ["02", "03", "04", "05"],
                "program_numbers": ["10.868"],
                "time_period": [{"start_date": f"{fy - 1}-10-01", "end_date": f"{fy}-09-30"}],
            },
            "fields": ["Award ID", "Award Amount", "Place of Performance State Code",
                       "Start Date", "Description"],
            "limit": 100, "sort": "Award ID", "order": "asc",
        }
        results: list[dict[str, Any]] = []
        page = 1
        while True:
            body["page"] = page
            resp = requests.post(USASPENDING_URL, json=body,
                                 headers={"User-Agent": USER_AGENT}, timeout=TIMEOUT)
            resp.raise_for_status()
            payload = resp.json()
            results.extend(
                {k: row.get(k) for k in body["fields"]} for row in payload["results"]
            )
            if not payload["page_metadata"]["hasNext"]:
                break
            page += 1
            time.sleep(0.15)
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(json.dumps({"fiscal_year": fy, "results": results}, indent=0))
        manifest.record(dest, source="USAspending.gov award search, Assistance Listing 10.868",
                        url=USASPENDING_URL, params=body["filters"], license_key="usaspending",
                        note="paged API responses concatenated; recipient fields not requested")


