def fetch_comstock(manifest: Manifest, states: list[str], building_types: list[str]) -> None:
    for st in states:
        for bt in building_types:
            name = f"up00-{st.lower()}-{bt}.csv"
            _download(
                manifest, RAW / "comstock" / st / name,
                url=f"{COMSTOCK_PREFIX}/state={st}/{name}",
                source="NREL End-Use Load Profiles for the U.S. Building Stock (ComStock)",
                license_key="comstock",
            )


def fetch_pvgis(manifest: Manifest, sites: list[Site], years: tuple[int, int],
                load_year: int) -> None:
    for site in sites:
        common = {"lat": site.latitude, "lon": site.longitude, "outputformat": "csv",
                  "components": 1, "angle": 0, "aspect": 0}
        _download(
            manifest, RAW / "pvgis" / f"{site.state}_nsrdb_{years[0]}_{years[1]}.csv",
            url=PVGIS_URL, source="EC JRC PVGIS 5.2 (NSRDB radiation, ERA5 meteorology)",
            license_key="pvgis",
            params={**common, "startyear": years[0], "endyear": years[1],
                    "raddatabase": "PVGIS-NSRDB"},
        )
        _download(
            manifest, RAW / "pvgis" / f"{site.state}_era5_{load_year}.csv",
            url=PVGIS_URL, source="EC JRC PVGIS 5.2 (ERA5)", license_key="pvgis",
            params={**common, "startyear": load_year, "endyear": load_year,
                    "raddatabase": "PVGIS-ERA5"},
            note="temperature for the load-profile year only",
        )
        time.sleep(0.2)


def _haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dphi = p2 - p1
    dlmb = math.radians(lon2 - lon1)
    a = math.sin(dphi / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dlmb / 2) ** 2
    return 2 * 6371.0 * math.asin(math.sqrt(a))


def isd_lite_coverage(raw: bytes) -> float:
    """Fraction of the hours of a year with a non-missing air temperature."""
    text = gzip.decompress(raw).decode("ascii", errors="replace")
    valid = 0
    for line in text.splitlines():
        parts = line.split()
        if len(parts) >= 5 and parts[4] != "-9999":
            valid += 1
    return valid / 8760.0


def fetch_isd(manifest: Manifest, sites: list[Site], years: list[int],
              min_coverage: float, max_candidates: int) -> dict[str, dict[str, Any]]:
    """Select, per site, the nearest ISD station with adequate coverage in every year."""
    hist = _download(
        manifest, RAW / "isd" / "isd-history.csv", url=f"{ISD_BASE}/isd-history.csv",
        source="NOAA NCEI Integrated Surface Database station history", license_key="isd",
    )
    rows = list(csv.DictReader(io.StringIO(hist.read_text(encoding="latin-1"))))
    selection_path = RAW / "isd" / "station_selection.json"
    selection: dict[str, dict[str, Any]] = {}
    if selection_path.exists():
        selection = json.loads(selection_path.read_text())
    first, last = min(years), max(years)
    for site in sites:
        if site.state in selection and all(
            (RAW / "isd_lite" / f"{selection[site.state]['station']}-{y}.gz").exists()
            for y in years
        ):
            continue
        candidates: list[tuple[float, dict[str, str]]] = []
        for r in rows:
            if r["CTRY"] != "US" or r["STATE"] != site.state or not r["LAT"] or not r["LON"]:
                continue
            if r["BEGIN"] > f"{first}0101" or r["END"] < f"{last}1231":
                continue
            if r["USAF"] == "999999":
                continue
            d = _haversine_km(site.latitude, site.longitude, float(r["LAT"]), float(r["LON"]))
            candidates.append((d, r))
        candidates.sort(key=lambda t: t[0])
        chosen: dict[str, Any] | None = None
        for dist, r in candidates[:max_candidates]:
            station = f"{r['USAF']}-{r['WBAN']}"
            blobs: dict[int, bytes] = {}
            ok = True
            for y in years:
                try:
                    resp = _get(f"{ISD_LITE_BASE}/{y}/{station}-{y}.gz", retries=2)
                except RuntimeError:
                    ok = False
                    break
                if resp.content[:2] != b"\x1f\x8b":
                    ok = False
                    break
                if isd_lite_coverage(resp.content) < min_coverage:
                    ok = False
                    break
                blobs[y] = resp.content
            if not ok:
                continue
            for y, blob in blobs.items():
                dest = RAW / "isd_lite" / f"{station}-{y}.gz"
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_bytes(blob)
                manifest.record(
                    dest, source="NOAA NCEI ISD-Lite",
                    url=f"{ISD_LITE_BASE}/{y}/{station}-{y}.gz", params=None,
                    license_key="isd",
                )
            chosen = {"station": station, "name": r["STATION NAME"],
                      "latitude": float(r["LAT"]), "longitude": float(r["LON"]),
                      "distance_km": round(dist, 1)}
            break
        if chosen is None:
            raise RuntimeError(f"no ISD station with adequate coverage for {site.state}")
        selection[site.state] = chosen
        selection_path.write_text(json.dumps(selection, indent=2, sort_keys=True) + "\n")
    return selection


