def fetch_all(include_large: bool = True) -> None:
    cfg, sites = load_sites()
    manifest = Manifest()
    years = (int(cfg["radiation_years"][0]), int(cfg["radiation_years"][1]))
    load_year = int(cfg["load_profile_year"])
    try:
        fetch_federal_register(manifest)
        fetch_eia_prices(manifest)
        fetch_pvwatts_reference(manifest)
        fetch_oversight_documents(manifest)
        manifest.save()
        if include_large:
            fetch_usaspending(manifest, [2021, 2022, 2023])
            manifest.save()
            fetch_isd(manifest, sites, [*range(years[0], years[1] + 1), load_year],
                      float(cfg["processing"]["station_min_coverage"]),
                      int(cfg["processing"]["station_max_candidates"]))
            manifest.save()
            fetch_pvgis(manifest, sites, years, load_year)
            manifest.save()
            fetch_comstock(manifest, [s.state for s in sites],
                           list(cfg["comstock_building_types"]))
    finally:
        manifest.save()
